#!/usr/bin/env python3
"""Regenerates app/theme-hex.css: one CSS variable per hard-coded hex colour used in
components (--h-rrggbb, RGB triplet). Light value = the original hex; dark value =
lightness-flipped variant (pale -> dark tint, dark ink -> light ink, mid accents
lifted so they stay legible on the dark paper).
Usage: python3 scripts/theme-hex-vars.py  (run from repo root)"""
import colorsys, os, re, sys
ROOT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..')
SCAN = ['app', 'components', 'lib']
SKIP = ('lib/manim', 'lib/messaging/emailLayout', 'lib/practice/worksheetPdf', 'app/theme-hex.css')
# also pick up already-converted references (bg-h-xxxxxx, --h-xxxxxx) so re-running is stable
REF = re.compile(r'(?<![\w])(?:--)?h-([0-9a-f]{6})(?![\w])')
HEX = re.compile(r'#([0-9a-fA-F]{6}|[0-9a-fA-F]{3})(?![0-9a-zA-Z_-])')

def expand(h):
    h = h.lower()
    return ''.join(c * 2 for c in h) if len(h) == 3 else h

def to_dark(h):
    r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
    hh, l, s = colorsys.rgb_to_hls(r, g, b)
    l2 = 0.07 + (1 - l) * 0.86
    if l2 < 0.3: s *= 0.35      # keep dark "paper" backgrounds close to neutral
    elif l2 > 0.55: s *= 0.85   # lifted inks/accents: a touch less saturated
    out = lambda L: tuple(round(x * 255) for x in colorsys.hls_to_rgb(hh, L, s))
    if 0.2 <= l <= 0.72:
        # ink/accent colours: guarantee >= 4.5:1 against the dark paper so text,
        # lines and labels drawn in them stay readable
        while contrast(out(l2), DARK_PAPER) < 4.5 and l2 < 0.95:
            l2 += 0.01
    return out(l2)

DARK_PAPER = (31, 28, 22)  # faf7f0 flipped (the sims' paper background)

def lum(rgb):
    f = lambda v: (v / 12.92) if v <= .03928 else ((v + .055) / 1.055) ** 2.4
    r, g, b = (f(x / 255) for x in rgb)
    return .2126 * r + .7152 * g + .0722 * b

def contrast(a, b):
    x, y = lum(a), lum(b)
    return (max(x, y) + .05) / (min(x, y) + .05)

def collect():
    found = {}
    for top in SCAN:
        for dp, _, fs in os.walk(os.path.join(ROOT, top)):
            for f in fs:
                if not f.endswith(('.ts', '.tsx', '.css')): continue
                p = os.path.join(dp, f)
                rel = os.path.relpath(p, ROOT).replace(os.sep, '/')
                if rel.startswith(SKIP): continue
                text = open(p, encoding='utf-8').read()
                for m in list(HEX.finditer(text)) + list(REF.finditer(text)):
                    found[expand(m.group(1))] = found.get(expand(m.group(1)), 0) + 1
    return found

if __name__ == '__main__':
    found = collect()
    if '--report' in sys.argv:
        paper = DARK_PAPER
        for h, n in sorted(found.items(), key=lambda kv: -kv[1])[:30]:
            d = to_dark(h)
            print(h, n, '#%02x%02x%02x' % d, 'vs dark paper %.1f' % contrast(d, paper))
        sys.exit()
    light, dark = [], []
    for h in sorted(found):
        rgb = tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))
        light.append(f'  --h-{h}: {rgb[0]} {rgb[1]} {rgb[2]};')
        d = to_dark(h)
        dark.append(f'  --h-{h}: {d[0]} {d[1]} {d[2]};')
    L, D = '\n'.join(light), '\n'.join(dark)
    css = ('/* GENERATED by scripts/theme-hex-vars.py - do not edit by hand.\n'
           ' * One variable per hard-coded hex colour (light = original, dark = lightness-flipped). */\n'
           f':root {{\n{L}\n}}\n\n'
           f'@media (prefers-color-scheme: dark) {{\n  :root:not([data-theme="light"]) {{\n' +
           '\n'.join('  ' + x for x in dark) + '\n  }\n}\n\n'
           f':root[data-theme="dark"] {{\n{D}\n}}\n\n'
           f'.theme-light {{\n{L}\n}}\n')
    open(os.path.join(ROOT, 'app/theme-hex.css'), 'w').write(css)
    import json
    open(os.path.join(ROOT, 'app/theme-hex.json'), 'w').write(json.dumps(sorted(found)) + '\n')
    print(len(found), 'colours')
